/// Accessibility identifiers of the menu bar menu items.
enum MenuBarAccessibilityIdentifier {
    /// The `Let it snow` toggle.
    static let letItSnow: String = "menuBar.letItSnowToggle"
    /// The `Clear snow` button.
    static let clearSnow: String = "menuBar.clearSnowButton"
    /// The `Quit MacSnow` button.
    static let quit: String = "menuBar.quitButton"
}
